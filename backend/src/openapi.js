for (const [path, method, summary, roles] of endpoints) {
  paths[path] ||= {};
  paths[path][method] = {
    summary,
    description: `Access: ${roles}.`,
    ...(roles === "Public" ? {} : { security: [{ bearerAuth: [] }] }),
    responses: {
      200: { description: "Request completed successfully" },
      400: { description: "Invalid request" },
      401: { description: "Authentication required" },
      403: { description: "Role or database permission denied" },
      404: { description: "Resource not found" },
    },
  };
}

